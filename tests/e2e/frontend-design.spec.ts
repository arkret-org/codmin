import { test, expect } from '@playwright/test';
import { setupLayout, layoutIds } from './layout-fixtures';

test('policy uses boolean and bounded integer controls while preserving typed requests', async ({ page }) => {
  const errors = await setupLayout(page);
  const writes: any[] = [];
  await page.route('**/_coland/self/policies', async route => {
    if (route.request().method() !== 'POST') return route.fallback();
    const body = route.request().postDataJSON();
    writes.push(body);
    return route.fulfill({ json: { policy_id: 'created-policy', owner: layoutIds.actor, scope: body.scope, subject_ref: body.subject_ref, policy_kind: body.policy_kind, payload: { effect: body.effect, actions: body.actions, resource: body.resource, obligations: body.obligations }, active: body.active, updated_at: '2026-11-14T00:00:00.000Z' } });
  });
  await page.goto('/policy');
  await expect(page.getByRole('checkbox', { name: 'Include inactive policies', exact: true })).not.toBeChecked();
  const create = page.locator('.admin-compact-action').filter({ has: page.getByRole('button', { name: 'Create', exact: true }).and(page.locator('[aria-expanded]')) });
  await create.getByRole('button', { name: 'Create', exact: true }).and(page.locator('[aria-expanded]')).click();
  const form = create.locator('.admin-action-form');
  await form.getByRole('textbox', { name: 'Name', exact: true }).fill('Typed form example');
  await page.getByRole('dialog').getByRole('button', { name: 'Close', exact: true }).click();
  const createTrigger = create.getByRole('button', { name: 'Create', exact: true }).and(page.locator('[aria-expanded]'));
  await expect(createTrigger).toBeFocused();
  await createTrigger.click();
  await expect(form.getByRole('textbox', { name: 'Name', exact: true })).toHaveValue('Typed form example');
  const enabled = form.getByRole('checkbox', { name: 'Enabled', exact: true });
  await expect(enabled).toBeChecked();
  await enabled.uncheck();
  const priority = form.getByRole('spinbutton', { name: 'Priority', exact: true });
  await priority.fill('2147483648');
  const submit = form.getByRole('button', { name: 'Create', exact: true });
  await expect(submit).toBeDisabled();
  await expect(form).toContainText('Enter a value within the stated range.');
  await priority.fill('-');
  await expect(submit).toBeDisabled();
  expect(writes).toHaveLength(0);
  await priority.fill('42');
  await expect(submit).toBeDisabled();
  await form.getByRole('checkbox', { name: 'I reviewed the scopes and subjects: * or an empty value matches all.', exact: true }).check();
  await form.getByRole('textbox', { name: 'Subject reference', exact: true }).fill(layoutIds.realm);
  await expect(submit).toBeDisabled();
  await expect(form.getByRole('checkbox', { name: 'I reviewed the scopes and subjects: * or an empty value matches all.', exact: true })).not.toBeChecked();
  await form.getByRole('checkbox', { name: 'I reviewed the scopes and subjects: * or an empty value matches all.', exact: true }).check();
  await expect(submit).toBeEnabled();
  await page.screenshot({ path: test.info().outputPath('policy-typed-desktop.png'), fullPage: true });
  await submit.click();
  await expect.poll(() => writes.length).toBe(1);
  await expect(form.locator('.action-message')).toContainText('Completed');
  expect(writes[0].active).toBe(false);
  expect(writes[0].resource.priority).toBe(42);
  expect(writes[0].subject_ref).toBe(layoutIds.realm);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath('policy-typed-mobile.png'), fullPage: true });
  expect(errors).toEqual([]);
});

test('dangerous operation identifies its target, cancels without a write, and keeps failures actionable', async ({ page }) => {
  const errors = await setupLayout(page);
  let writes = 0;
  await page.route('**/_coauth/admin/accounts/*/devices/*/revoke', route => {
    writes++;
    return route.fulfill({ status: 503, contentType: 'application/problem+json', body: JSON.stringify({ type: 'about:blank', title: 'Temporarily unavailable', status: 503, detail: 'Please try again.' }) });
  });
  await page.goto(`/coauth/accounts/${layoutIds.account}/devices`);
  const trigger = page.getByRole('button', { name: 'Revoke', exact: true }).and(page.locator('[aria-expanded]')).first();
  await trigger.click();
  const form = page.locator('.admin-compact-action').filter({ has: trigger }).locator('.admin-action-form');
  await expect(form).toContainText(layoutIds.device);
  await expect(form).toContainText('What changes');
  const phrase = form.getByRole('textbox', { name: 'Confirmation phrase', exact: true });
  const reason = form.getByRole('textbox', { name: 'Reason / ticket', exact: true });
  await phrase.fill(layoutIds.device.slice(-4));
  await reason.fill('Operator requested device revocation.');
  await form.getByRole('button', { name: 'Cancel confirmation', exact: true }).click();
  await expect(phrase).toHaveValue('');
  await expect(reason).toHaveValue('');
  expect(writes).toBe(0);
  await phrase.fill(layoutIds.device.slice(-4));
  await reason.fill('Operator requested device revocation.');
  await form.getByRole('button', { name: 'Revoke', exact: true }).click();
  await expect(form.locator('.action-message')).toContainText('503');
  await expect(form.getByRole('button', { name: 'Revoke', exact: true })).toBeEnabled();
  await expect(reason).toHaveValue('Operator requested device revocation.');
  expect(writes).toBe(1);
  await page.screenshot({ path: test.info().outputPath('revoke-failure-desktop.png'), fullPage: true });
  expect(errors).toEqual([]);
});
